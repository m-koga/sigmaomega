// Generate src/ts/element-ids.d.ts: the element type of every id in the page, for $(id) in src/ts.
// Ids are collected from src/index.html and from the HTML written in src/ts/*.ts:
//   <input id="Tsim" ...>      → "Tsim": HTMLInputElement
//   <input id="in-${k}" ...>   → [id: `in-${string}`]: HTMLInputElement   (ids built in the script)
// Called by scripts/build.ts; the file is written only when it changes.
import fs from 'node:fs';
import path from 'node:path';

const SRC = path.join(import.meta.dirname, '..', 'src');
const OUT = path.join(SRC, 'ts', 'element-ids.d.ts');

const TYPES: Record<string, string> = {
  input: 'HTMLInputElement',
  select: 'HTMLSelectElement',
  textarea: 'HTMLTextAreaElement',
  canvas: 'HTMLCanvasElement',
  button: 'HTMLButtonElement',
  div: 'HTMLDivElement',
  span: 'HTMLSpanElement',
  label: 'HTMLLabelElement',
  table: 'HTMLTableElement',
  p: 'HTMLParagraphElement',
  b: 'HTMLElement',
  code: 'HTMLElement',
  h2: 'HTMLHeadingElement',
  h3: 'HTMLHeadingElement',
  section: 'HTMLElement',
  header: 'HTMLElement',
  details: 'HTMLDetailsElement',
  summary: 'HTMLElement',
  a: 'HTMLAnchorElement',
  ul: 'HTMLUListElement',
  li: 'HTMLLIElement',
  svg: 'SVGSVGElement',
  option: 'HTMLOptionElement',
  tr: 'HTMLTableRowElement',
  td: 'HTMLTableCellElement',
};
const typeOf = (tag: string) => TYPES[tag] || `HTMLElementTagNameMap['${tag}']`;

function generate(): string {
  const files = [
    path.join(SRC, 'index.html'),
    ...fs
      .readdirSync(path.join(SRC, 'ts'))
      .filter(f => f.endsWith('.ts') && !f.endsWith('.d.ts'))
      .sort()
      .map(f => path.join(SRC, 'ts', f)),
  ];
  const ids = new Map<string, { t: string; where: string }>(),
    patterns = new Map<string, { t: string; where: string }>();
  const add = (map: typeof ids, key: string, tag: string, where: string) => {
    const t = typeOf(tag),
      cur = map.get(key);
    if (cur && cur.t !== t)
      cur.t = cur.t.split(' | ').includes(t) ? cur.t : cur.t + ' | ' + t; // the same id on different tags
    else if (!cur) map.set(key, { t, where });
  };
  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8'),
      where = path.relative(SRC, file).replace(/\\/g, '/');
    for (const m of text.matchAll(/<([a-zA-Z][a-zA-Z0-9]*)\b[^<>]*?\sid=(["'])([^"']*)\2/g)) {
      const tag = m[1].toLowerCase(),
        id = m[3];
      if (!id.includes('${')) {
        add(ids, id, tag, where);
        continue;
      }
      // template ids: every ${...} becomes ${string}
      add(patterns, id.replace(/\$\{[^}]*\}/g, '${string}'), tag, where);
    }
  }
  const q = (s: string) => JSON.stringify(s);
  const lines = [
    '// SPDX-License-Identifier: Apache-2.0',
    '// Copyright 2026 Masanobu Koga',
    '// Generated by scripts/gen-element-ids.ts from the ids in src/index.html and src/ts/*.ts (npm run build).',
    '// Do not edit: add or change the id in the HTML instead.',
    '',
    '/** Element type of every id in the page: $(id) accepts these ids only */',
    'interface ElementById {',
    ...[...ids].sort((a, b) => a[0].localeCompare(b[0])).map(([id, v]) => `  ${q(id)}: ${v.t};`),
    '  // ids built in the script',
    ...[...patterns].sort((a, b) => a[0].localeCompare(b[0])).map(([p, v]) => `  [id: \`${p}\`]: ${v.t};`),
    '}',
    '',
  ];
  return lines.join('\n');
}

// Write the file if it changed; returns true when it was up to date
function update({ check = false } = {}) {
  const text = generate(),
    cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur === text) return true;
  if (!check) fs.writeFileSync(OUT, text);
  return false;
}

if (process.argv[1] === import.meta.filename) {
  update();
  console.log('src/ts/element-ids.d.ts written');
}
export { generate, update, OUT };
