// Generate tests/app-api.d.ts: the types of the page script as the tests see it.
//  - AppApi: every exported name of src/ts with its type, e.g.  simulate: typeof import('../src/ts/08-simulation.ts').simulate;
//    tests/harness.ts gives the tests an object of this type (api.S, api.simulate, ...).
//  - the same names declared as globals: in the built page they are globals, which the browser tests use in
//    code run inside the page (page.evaluate).
// The names come from TypeScript's declaration output for src/ts (written to a temporary folder).
// Run by npm run typecheck before the scripts and tests are type-checked; the file is written only when it changes.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = path.join(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'tests', 'app-api.d.ts');

// Exported values of one .d.ts file: functions, and every declarator of const/let/var statements
function namesOf(dts: string): string[] {
  const names: string[] = [];
  for (const m of dts.matchAll(/^export declare (?:async )?function ([\w$]+)/gm)) names.push(m[1]);
  for (const m of dts.matchAll(/^export declare (?:const|let|var) /gm)) {
    // split the statement at commas outside brackets, generics and strings; each part starts with a name
    let depth = 0,
      quote = '',
      start = m.index + m[0].length;
    for (let i = start; i < dts.length; i++) {
      const c = dts[i];
      if (quote) {
        if (c === quote && dts[i - 1] !== '\\') quote = '';
        continue;
      }
      if (c === '"' || c === "'" || c === '`') quote = c;
      else if (c === '(' || c === '[' || c === '{' || c === '<') depth++;
      else if (c === ')' || c === ']' || c === '}' || (c === '>' && dts[i - 1] !== '=')) depth--;
      else if (depth === 0 && (c === ',' || c === ';')) {
        const n = dts
          .slice(start, i)
          .trim()
          .match(/^([\w$]+)/);
        if (n) names.push(n[1]);
        if (c === ';') break;
        start = i + 1;
      }
    }
  }
  return names;
}

function generate(): string {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'app-api-'));
  try {
    const r = spawnSync(
      'npx',
      [
        'tsc',
        '-p',
        ROOT,
        '--noEmit',
        'false',
        '--declaration',
        '--emitDeclarationOnly',
        '--rootDir',
        path.join(ROOT, 'src', 'ts'),
        '--outDir',
        tmp,
      ],
      { cwd: ROOT, encoding: 'utf8', shell: process.platform === 'win32' },
    );
    if (r.status !== 0) throw new Error('declaration output of src/ts failed:\n' + r.stdout + r.stderr);
    const entries: [string, string][] = []; // [name, module file]
    for (const f of fs.readdirSync(tmp).sort())
      if (f.endsWith('.d.ts') && /^\d/.test(f))
        namesOf(fs.readFileSync(path.join(tmp, f), 'utf8')).forEach(n =>
          entries.push([n, f.replace(/\.d\.ts$/, '.ts')]),
        );
    entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
    return [
      '// SPDX-License-Identifier: Apache-2.0',
      '// Copyright 2026 Masanobu Koga',
      '// Generated by scripts/gen-app-api.ts from the exports of src/ts (npm run typecheck). Do not edit.',
      '',
      '/** The page script as the tests see it (tests/harness.ts): every exported name of src/ts with its type */',
      'interface AppApi {',
      ...entries.map(([n, f]) => `  ${n}: typeof import('../src/ts/${f}').${n};`),
      '}',
      '',
      '// In the built page these names are globals (one classic script): for code run in the page (page.evaluate)',
      ...entries.map(([n]) => `declare var ${n}: AppApi['${n}'];`),
      '',
    ].join('\n');
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

function update(): boolean {
  const text = generate(),
    cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur === text) return true;
  fs.writeFileSync(OUT, text);
  return false;
}

if (process.argv[1] === import.meta.filename) update();
export { generate, update, namesOf };
