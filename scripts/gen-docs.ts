// Generate the English (CHANGELOG.md) and Japanese (CHANGELOG.ja.md) change logs
// from the CHANGELOG array in src/ts/01-changelog.ts, read from the built index.html (en: English, ja: Japanese),
// and the citation file CITATION.cff (its version and date are those of the newest entry).
//   Usage: npm run docs
//          node scripts/gen-docs.ts --notes [X.Y.Z]   (release notes of a version, default the newest, to stdout;
//                                                     used by .github/workflows/release.yml)
import fs from 'node:fs';
import path from 'node:path';
import { load } from '../tests/harness.ts';

const ROOT = path.join(import.meta.dirname, '..');

function render(changelog: { v: string; d: string; en: string[]; ja: string[] }[], lang: 'en' | 'ja'): string {
  const ja = lang === 'ja';
  const head = ja
    ? [
        '# 更新履歴',
        '',
        '[English](CHANGELOG.md) | 日本語',
        '',
        '版番号は[セマンティック バージョニング](https://semver.org/lang/ja/)に従います（機能追加：2 番目、修正・文言：3 番目の数字を上げる）。',
        '',
        '> このファイルは `npm run docs` で `src/ts/01-changelog.ts` の更新履歴から生成されます。直接編集しないでください。',
        '',
      ]
    : [
        '# Change Log',
        '',
        'English | [日本語](CHANGELOG.ja.md)',
        '',
        'Version numbers follow [Semantic Versioning](https://semver.org/) (the second number for new features, the third for fixes and wording).',
        '',
        '> This file is generated from the change log in `src/ts/01-changelog.ts` by `npm run docs`. Do not edit it directly.',
        '',
      ];
  const body = [];
  for (const e of changelog) {
    body.push(ja ? `## v${e.v}（${e.d}）` : `## v${e.v} (${e.d})`);
    for (const item of ja ? e.ja : e.en) body.push('- ' + item);
    body.push('');
  }
  return head.concat(body).join('\n');
}

type Entry = { v: string; d: string; en: string[]; ja: string[] };
const changelog = (): Entry[] => JSON.parse(JSON.stringify(load().api.CHANGELOG));
const pkg = () =>
  JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')) as { license: string; description: string };
export const REPO = 'https://github.com/m-koga/sigmaomega';
export const SITE = 'https://m-koga.github.io/sigmaomega/';

// CITATION.cff (Citation File Format 1.2.0): how to cite the software; GitHub shows it as "Cite this repository",
// and Zenodo uses it for the DOI of each release
function citation(e: Entry): string {
  return [
    '# Generated by scripts/gen-docs.ts (npm run docs) from package.json and the change log. Do not edit.',
    'cff-version: 1.2.0',
    'message: "If you use this software, please cite it as below."',
    'type: software',
    'title: "SigmaOmega — Feedback Control Simulator"',
    'abstract: >-',
    '  Teaching software for control engineering that runs in the browser: the time response,',
    '  Bode and Nyquist plots, pole-zero map and root locus of a single-loop feedback control system,',
    '  with PID tuning rules, design specifications and parameter sweeps.',
    'authors:',
    '  - family-names: Koga',
    '    given-names: Masanobu',
    '    affiliation: Kyushu Institute of Technology',
    `version: ${e.v}`,
    `date-released: ${e.d}`,
    `license: ${pkg().license}`,
    `repository-code: "${REPO}"`,
    `url: "${SITE}"`,
    'keywords:',
    ...[
      'control engineering',
      'feedback control',
      'PID control',
      'Bode plot',
      'Nyquist plot',
      'root locus',
      'education',
    ].map(k => `  - ${k}`),
    '',
  ].join('\n');
}

// Release notes of version v (both languages, with the files of the release)
export function releaseNotes(v?: string): string {
  const cl = changelog(),
    e = v ? cl.find(x => x.v === v.replace(/^v/, '')) : cl[0];
  if (!e) throw new Error(`version ${v} is not in the change log`);
  return [
    `SigmaOmega — Feedback Control Simulator v${e.v} (${e.d})`,
    '',
    ...e.en.map(i => `- ${i}`),
    '',
    '### 日本語',
    '',
    ...e.ja.map(i => `- ${i}`),
    '',
    '### Files / ファイル',
    '',
    `- \`index.html\`: the whole simulator in one file; open it in a browser (it loads fonts and MathJax from the internet). / シミュレーター全体の 1 ファイル。ブラウザで開いて使う（フォントと MathJax をインターネットから読み込む）。`,
    `- \`sigmaomega-site-v${e.v}.zip\`: the web site (the page with its manifest and icons) for your own server. / 自分のサーバーに置くためのサイト一式（ページ、マニフェスト、アイコン）。`,
    '',
    `Online: ${SITE} · Change log: ${REPO}/blob/v${e.v}/CHANGELOG.md`,
    '',
  ].join('\n');
}

// Generated content (also used by the tests)
function generate() {
  const cl = changelog();
  return { 'CHANGELOG.md': render(cl, 'en'), 'CHANGELOG.ja.md': render(cl, 'ja'), 'CITATION.cff': citation(cl[0]) };
}

if (process.argv[1] === import.meta.filename && process.argv[2] === '--notes') {
  process.stdout.write(releaseNotes(process.argv[3]));
} else if (process.argv[1] === import.meta.filename) {
  for (const [name, text] of Object.entries(generate())) {
    fs.writeFileSync(path.join(ROOT, name), text);
    console.log('Generated: ' + name);
  }
}

export { generate };
