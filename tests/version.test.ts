// Tests for consistency of version numbers and the change log
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { load } from './harness.ts';
import { generate } from '../scripts/gen-docs.ts';

const { api, html } = load();
const cmp = (a: string, b: string) => {
  const x = a.split('.').map(Number),
    y = b.split('.').map(Number);
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
};

test('the version in <meta>, the page, and the first change log entry match', () => {
  const meta = html.match(/<meta name="version" content="([\d.]+)">/)?.[1];
  assert.equal(meta, api.APP_VERSION);
  assert.equal(api.CHANGELOG[0].v, api.APP_VERSION);
});

test('change log versions follow semantic versioning and are newest first', () => {
  const vs = api.CHANGELOG.map(e => e.v);
  vs.forEach(v => assert.match(v, /^\d+\.\d+\.\d+$/));
  for (let i = 1; i < vs.length; i++) assert.ok(cmp(vs[i - 1], vs[i]) > 0, `order of ${vs[i - 1]} and ${vs[i]}`);
  api.CHANGELOG.forEach(e => assert.ok(e.en.length > 0 && e.ja.length > 0, `v${e.v} has no items`));
});

test('each change log entry has the same number of English (en) and Japanese (ja) items', () => {
  api.CHANGELOG.forEach(e => {
    assert.ok(
      Array.isArray(e.ja) && e.ja.length === e.en.length,
      `v${e.v}: number of Japanese items differs from English`,
    );
    e.en.forEach(x =>
      assert.ok(x && !/[\u3040-\u30ff\u4e00-\u9fff]/.test(x), `v${e.v}: English item contains Japanese: ${x}`),
    );
  });
});

test('CHANGELOG.md (English) and CHANGELOG.ja.md (Japanese) are up to date (generated by npm run docs)', () => {
  for (const [name, text] of Object.entries(generate())) {
    const file = path.join(import.meta.dirname, '..', name);
    assert.ok(fs.existsSync(file), `${name} is missing (run npm run docs)`);
    assert.equal(fs.readFileSync(file, 'utf8'), text, `${name} is out of date (run npm run docs)`);
  }
});
